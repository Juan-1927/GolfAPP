    (2, 'palo', 'Paradym', 'Callaway', 349.00, '2026-10-05T18:05:00Z')
ON CONFLICT (id) DO NOTHING;

INSERT INTO palos (producto_id, tipo, material, flexibilidad)
SELECT datos.id, datos.tipo, datos.material, datos.flexibilidad
FROM (
    VALUES
        (1::BIGINT, 'Driver', 'Grafito', 'Regular'),
        (2::BIGINT, 'Madera', 'Grafito', 'Regular')
) AS datos(id, tipo, material, flexibilidad)
JOIN productos p
    ON p.id = datos.id
   AND p.categoria = 'palo'
ON CONFLICT (producto_id) DO NOTHING;

-- 7. Sincronización automática de la secuencia del IDENTITY para futuros registros
SELECT setval(
    pg_get_serial_sequence('productos', 'id'),
    GREATEST(COALESCE((SELECT MAX(id) FROM productos), 1), 1),
    EXISTS (SELECT 1 FROM productos)
);

COMMIT;
