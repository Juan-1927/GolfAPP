BEGIN;

-- 1. Tabla base para todos los productos
CREATE TABLE IF NOT EXISTS productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria TEXT NOT NULL
        CHECK (categoria IN ('palo', 'equipo', 'vestimenta')),
    nombre TEXT NOT NULL,
    marca TEXT NOT NULL,
    precio NUMERIC(10, 2) NOT NULL
        CHECK (precio >= 0),
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Restricción para garantizar la relación compuesta con las tablas hijas
    CONSTRAINT uq_productos_id_categoria UNIQUE (id, categoria)
);

-- 2. Tabla específica para Palos
CREATE TABLE IF NOT EXISTS palos (
    producto_id BIGINT PRIMARY KEY,
    categoria TEXT NOT NULL DEFAULT 'palo'
        CHECK (categoria = 'palo'),
    tipo TEXT NOT NULL,
    material TEXT NOT NULL,
    flexibilidad TEXT NOT NULL,

    CONSTRAINT fk_palos_producto
        FOREIGN KEY (producto_id, categoria)
        REFERENCES productos (id, categoria)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

-- 3. Tabla específica para Equipos
CREATE TABLE IF NOT EXISTS equipos (
    producto_id BIGINT PRIMARY KEY,
    categoria TEXT NOT NULL DEFAULT 'equipo'
        CHECK (categoria = 'equipo'),
    tipo TEXT NOT NULL,
    descripcion TEXT NOT NULL,

    CONSTRAINT fk_equipos_producto
        FOREIGN KEY (producto_id, categoria)
        REFERENCES productos (id, categoria)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

-- 4. Tabla específica para Vestimenta
CREATE TABLE IF NOT EXISTS vestimenta (
    producto_id BIGINT PRIMARY KEY,
    categoria TEXT NOT NULL DEFAULT 'vestimenta'
        CHECK (categoria = 'vestimenta'),
    talla TEXT NOT NULL,
    color TEXT NOT NULL,

    CONSTRAINT fk_vestimenta_producto
        FOREIGN KEY (producto_id, categoria)
        REFERENCES productos (id, categoria)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

-- 5. Índice para optimizar las consultas filtradas por categoría
CREATE INDEX IF NOT EXISTS idx_productos_categoria
    ON productos (categoria);

-- 6. Inserción idempotente de los dos palos de ejemplo del proyecto
INSERT INTO productos (
    id, categoria, nombre, marca, precio, fecha_creacion
)
VALUES
